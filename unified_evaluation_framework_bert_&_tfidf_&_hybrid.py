def plot_top_k_overlap(tfidf_scores, bert_scores, k=15):
    tfidf_dict = dict(tfidf_scores[:k])
    bert_dict = dict(bert_scores[:k])

    all_candidates = sorted(set(tfidf_dict) | set(bert_dict))

    tfidf_vals = [tfidf_dict.get(name, 0) for name in all_candidates]
    bert_vals = [bert_dict.get(name, 0) for name in all_candidates]

    # Find overlaps to color-code
    overlap = set(tfidf_dict.keys()) & set(bert_dict.keys())

    x = np.arange(len(all_candidates))
    width = 0.35

    plt.figure(figsize=(14, 6))

    # Custom colors: green if in both, otherwise original color
    tfidf_colors = ['green' if name in overlap else 'orange' for name in all_candidates]
    bert_colors  = ['green' if name in overlap else 'skyblue' for name in all_candidates]

    tfidf_bars = plt.bar(x - width/2, tfidf_vals, width, label='TF-IDF + spaCy', color=tfidf_colors)
    bert_bars  = plt.bar(x + width/2, bert_vals, width, label='BERT', color=bert_colors)

    plt.xticks(x, all_candidates, rotation=90)
    plt.xlabel("Candidates")
    plt.ylabel("Score")
    plt.title(f"Top-{k} Score Comparison (Green = Common in Both)")
    plt.legend()

    # Add score labels above bars
    for i in range(len(all_candidates)):
        plt.text(x[i] - width/2, tfidf_vals[i] + 0.005, f"{tfidf_vals[i]:.2f}", ha='center', fontsize=8)
        plt.text(x[i] + width/2, bert_vals[i] + 0.005, f"{bert_vals[i]:.2f}", ha='center', fontsize=8)

    plt.tight_layout()
    plt.show()

